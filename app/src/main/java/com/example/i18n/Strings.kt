enum class AppLang { EN, AR }

val LocalAppLang = staticCompositionLocalOf { AppLang.EN }

fun AppLang.layoutDirection(): LayoutDirection =
    if (this == AppLang.AR) LayoutDirection.Rtl else LayoutDirection.Ltr

fun formatSar(amount: Double, lang: AppLang): String {
    val formatted = String.format(Locale.US, "%.2f", amount)
    return if (lang == AppLang.AR) "$formatted ر.س" else "$formatted SAR"
}

fun formatNumber(amount: Double): String = String.format(Locale.US, "%.2f", amount)

